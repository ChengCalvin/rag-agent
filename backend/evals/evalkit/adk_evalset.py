"""ADK evalsets and criteria generated from the case files (pure; design D7).

ADK eval scores tool trajectories only; content checks stay in the custom runner. One case file
is the single source, so the two cannot drift apart (STRUCT-5). Findings against the design,
checked against adk.dev and the installed google-adk 2.15.0:

* Persona: the orchestrator's first node overwrites the principal every turn from the
  `NOVAMART_USER` setting, so seeding `session_input.state` cannot select a persona (D7 said it
  would). Evalsets are therefore split per persona and `adk eval` is run once per persona with
  `NOVAMART_USER` set; the state stays empty.
* Arguments: a model-written `search_policy` query cannot be matched, and the published page
  documents no way around that. 2.15.0 has `ignore_args` and `match_type` on the criterion
  (undocumented on the page), so both are used and only tool names are compared.
* The default `response_match_score` (ROUGE against a reference reply) would apply if no criteria
  are given, so each config states `tool_trajectory_avg_score` alone.
* Multi-turn cases are not exported: one expected tool list per case cannot say which turn made
  which call. The custom runner covers them.
* Whether `adk eval` loads a `Workflow` root is still open (design.md, `adk-eval-workflow-root`);
  the custom runner reads tool calls from events as the fallback D7 names.
"""

import json
from collections.abc import Sequence

from evalkit.cases import Case

APP_NAME = "novamart_agent"
EVAL_USER = "eval"
IN_ORDER = "in_order"
EXACT = "exact"
_MATCH_TYPES = {IN_ORDER: "IN_ORDER", EXACT: "EXACT"}


def group_of(case: Case) -> str | None:
    """`in_order` (tools required), `exact` (none allowed) or None (not pinned, or multi-turn)."""
    tools = case.adk_expected_tools()
    if tools is None or len(case.turns) != 1:
        return None
    return EXACT if not tools else IN_ORDER


def criteria_file(group: str) -> dict[str, object]:
    """The criteria file for a group: the trajectory metric only, tool names only."""
    return {
        "criteria": {
            "tool_trajectory_avg_score": {
                "threshold": 1.0,
                "match_type": _MATCH_TYPES[group],
                "ignore_args": True,
            }
        }
    }


def _invocation(case: Case) -> dict[str, object]:
    tools = case.adk_expected_tools() or ()
    return {
        "invocation_id": case.case_id,
        "user_content": {"parts": [{"text": case.turns[0]}], "role": "user"},
        "intermediate_data": {
            "tool_uses": [{"name": name, "args": {}} for name in tools],
            "intermediate_responses": [],
        },
    }


def evalset(set_name: str, persona: str, group: str, cases: Sequence[Case]) -> dict[str, object]:
    """One evalset: the cases of one set, persona and group."""
    return {
        "eval_set_id": f"{set_name}_{persona}_{group}",
        "name": f"{set_name} / {persona} / {group}",
        "description": "Generated by evals/build_evalsets.py from cases/*.json. Do not edit.",
        "eval_cases": [
            {
                "eval_id": c.case_id,
                "conversation": [_invocation(c)],
                "session_input": {"app_name": APP_NAME, "user_id": EVAL_USER, "state": {}},
            }
            for c in cases
        ],
    }


def partition(cases: Sequence[Case]) -> dict[tuple[str, str, str], list[Case]]:
    """Cases keyed by (set, persona, group); cases that ADK cannot score are left out."""
    parts: dict[tuple[str, str, str], list[Case]] = {}
    for case in cases:
        group = group_of(case)
        if group is not None and case.fixture is None:
            parts.setdefault((case.set_name, case.persona, group), []).append(case)
    return parts


def evalset_files(cases: Sequence[Case]) -> dict[str, str]:
    """Relative path (under `evals/evalsets/`) to file text, for every file that is generated.

    Layout: `<group>/test_config.json` next to `<group>/<set>.<persona>.evalset.json` (ARCH-MOD-3).
    """
    files: dict[str, str] = {}
    for (set_name, persona, group), part in sorted(partition(cases).items()):
        files[f"{group}/{set_name}.{persona}.evalset.json"] = _dump(
            evalset(set_name, persona, group, part)
        )
        files[f"{group}/test_config.json"] = _dump(criteria_file(group))
    return files


def _dump(record: dict[str, object]) -> str:
    return json.dumps(record, indent=2, sort_keys=True) + "\n"
